package com.mycompany.dto;

/**
 * this is the data we want to pass from members table rather than exposing everything.
 *
 * @author m2505660
 */
public class MemberDto {

    private int id;
    private String firstName;
    private String lastName;

    public MemberDto(int id, String firstName, String lastName) {
        this.id = id;
        this.firstName = firstName;
        this.lastName = lastName;
    }

    public int getId() {
        return id;
    }

    public String getFirstName() {
        return firstName;
    }

    public String getLastName() {
        return lastName;
    }

}
